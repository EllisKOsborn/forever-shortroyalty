// Reads UI/Theme.lua and writes preview/theme.css + preview/theme.js, so the
// browser preview uses exactly the addon's colours, sizes, spacing and
// motion timings. The display font and the textures are embedded as data
// URLs so the preview also works when opened straight from the disk.
// Usage: node tools/preview-tokens.js
const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");
const lua = fs.readFileSync(path.join(ROOT, "UI", "Theme.lua"), "utf8");

// Body of "Theme.NAME = { ... }" (first level only).
function table(name) {
  const start = lua.indexOf("Theme." + name + " = {");
  if (start < 0) throw new Error("Theme." + name + " not found");
  let depth = 0, i = lua.indexOf("{", start);
  const from = i;
  for (; i < lua.length; i++) {
    if (lua[i] === "{") depth++;
    if (lua[i] === "}" && --depth === 0) break;
  }
  return lua.slice(from + 1, i).replace(/--[^\n]*/g, "");
}

const color = {};
for (const m of table("COLOR").matchAll(/(\w+)\s*=\s*\{\s*([\d.]+),\s*([\d.]+),\s*([\d.]+),\s*([\d.]+)\s*\}/g)) {
  color[m[1]] = [m[2], m[3], m[4], m[5]].map(Number);
}
const nums = (name) => {
  const out = {};
  for (const m of table(name).matchAll(/(\w+)\s*=\s*([\d.]+)/g)) out[m[1]] = Number(m[2]);
  return out;
};
const sizes = nums("SIZES");
const win = table("SIZES").match(/window\s*=\s*\{\s*(\d+),\s*(\d+)/);
sizes.windowW = Number(win[1]);
sizes.windowH = Number(win[2]);
const space = nums("SPACE");
sizes.contentW = sizes.windowW - sizes.sidebar - 2 * space.l; // as Theme.SIZES.contentW
const tokens = {
  color, space, size: nums("SIZE"), sizes, motion: nums("MOTION"), alpha: nums("ALPHA"),
  type: {},
};
for (const m of table("TYPE").matchAll(/(\w+)\s*=\s*\{\s*"(\w+)",\s*(\d+)/g)) tokens.type[m[1]] = [m[2], Number(m[3])];

const rgba = (c, a) => `rgba(${Math.round(c[0] * 255)}, ${Math.round(c[1] * 255)}, ${Math.round(c[2] * 255)}, ${a ?? c[3]})`;
const b64 = (f) => fs.readFileSync(path.join(ROOT, f)).toString("base64");

let css = "/* Generated by tools/preview-tokens.js from UI/Theme.lua. Do not edit. */\n";
css += `@font-face { font-family: "Chakra Petch SK"; font-weight: 600;
  src: url(data:font/ttf;base64,${b64("Media/Fonts/ChakraPetch-SemiBold.ttf")}) format("truetype"); }\n`;
css += `@font-face { font-family: "Inter SK"; font-weight: 400;
  src: url(data:font/ttf;base64,${b64("Media/Fonts/Inter-Regular.ttf")}) format("truetype"); }\n`;
css += ":root {\n";
for (const [k, c] of Object.entries(color)) css += `  --${k}: ${rgba(c)};\n`;
css += `  --accent-selected: ${rgba(color.accent, tokens.alpha.selected)};\n`;
css += `  --spark-alert: ${rgba(color.spark, tokens.alpha.alert)};\n`;
for (const [k, v] of Object.entries(tokens.space)) css += `  --sp-${k}: ${v}px;\n`;
for (const [k, v] of Object.entries(tokens.size)) css += `  --fs-${k}: ${v}px;\n`;
for (const [k, v] of Object.entries(sizes)) css += `  --sz-${k}: ${v}px;\n`;
for (const [k, v] of Object.entries(tokens.motion)) css += `  --mo-${k}: ${k === "openScale" ? v : v * 1000 + "ms"};\n`;
for (const t of ["crest", "arrow", "close", "dot", "ring", "star", "pill", "chevron", "icon-overview", "icon-roster",
  "icon-character", "icon-crafters", "icon-professions", "icon-settings", "icon-words"]) {
  css += `  --tex-${t}: url(data:image/png;base64,${b64("preview/img/" + t + ".png")});\n`;
}
css += "}\n";

fs.writeFileSync(path.join(ROOT, "preview", "theme.css"), css);
fs.writeFileSync(path.join(ROOT, "preview", "theme.js"),
  "// Generated by tools/preview-tokens.js from UI/Theme.lua. Do not edit.\nwindow.SK_THEME = " +
  JSON.stringify(tokens, null, 2) + ";\n");
console.log("wrote preview/theme.css and preview/theme.js:", Object.keys(color).length, "colours");
