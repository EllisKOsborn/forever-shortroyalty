// Writes Data/Words.lua for Short Words (v0.7.0): the daily/free answers and
// the list of words you may guess.
//
// Usage:
//   curl -o enable1.txt https://raw.githubusercontent.com/dolph/dictionary/master/enable1.txt
//   git clone --depth 1 https://github.com/en-wl/wordlist.git scowl
//   node tools/words.js enable1.txt scowl/data/scowl-pre.txt
//
// Sources (both free to use; credited in README):
// - ENABLE (Enhanced North American Benchmark Lexicon), public domain: every
//   five-letter word in it may be guessed.
// - SCOWL / English Speller Database by Kevin Atkinson (MIT-like licence,
//   notice in Data/Words.lua): answers are base words (no plural or past
//   forms) of size 35, its most common words, that are also in ENABLE.
// Then rude, crude, regional-slang and plural-looking words are removed by
// hand (BLOCK) and the answers are shuffled with a fixed seed, so the daily
// order is fixed but not alphabetical.
const fs = require("fs");
const path = require("path");

const [enableFile, scowlFile] = process.argv.slice(2);
if (!enableFile || !scowlFile) {
  console.error("usage: node tools/words.js enable1.txt scowl/data/scowl-pre.txt");
  process.exit(1);
}

const BLOCK = new Set((
  // rude, crude or hurtful
  "bitch whore pussy penis horny booty kinky semen sperm spunk prick queer lynch slave lusty tramp booby " +
  "enema urine vomit bawdy buxom harem sissy pansy thong " +
  // regional slang and odd ones
  "bogan galah chook cooee skite bluey youse bonze roman " +
  // plural-looking or plural-only
  "dregs eaves folks goods grits jeans mumps pants times tongs woods works yours"
).split(/\s+/));

const five = (w) => /^[a-z]{5}$/.test(w);
const enable = new Set(fs.readFileSync(enableFile, "utf8").split(/\r?\n/).map((w) => w.trim()).filter(five));

const best = new Map();
for (const line of fs.readFileSync(scowlFile, "utf8").split(/\n/)) {
  const m = line.match(/^(\d+) .*?\]: (?:_: )?([^<:]+?) </);
  if (!m) continue;
  const word = m[2].trim();
  if (five(word)) best.set(word, Math.min(best.get(word) ?? 999, Number(m[1])));
}
const answers = [...best].filter(([w, size]) => size <= 35 && enable.has(w) && !BLOCK.has(w)).map(([w]) => w).sort();

// mulberry32, fixed seed: the same order every time the file is generated.
let seed = 20261113;
const rand = () => {
  seed = (seed + 0x6d2b79f5) | 0;
  let t = seed;
  t = Math.imul(t ^ (t >>> 15), t | 1);
  t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
  return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
};
for (let i = answers.length - 1; i > 0; i--) {
  const j = Math.floor(rand() * (i + 1));
  [answers[i], answers[j]] = [answers[j], answers[i]];
}

const valid = [...new Set([...enable, ...answers])].sort();
// A list joined once at load ("a" .. "b" .. … nests too deep for Lua 5.1).
const chunk = (s) => "table.concat({\n" + s.match(/.{1,100}/g).map((x) => `\t"${x}",`).join("\n") + "\n})";

const lua = `-- GENERATED by tools/words.js. Do not edit by hand.
-- Short Words (v0.7.0) word lists, as one long string of five-letter words
-- each (no separators): looked up by position, so nothing is unpacked into
-- tables.
--
-- ANSWERS (${answers.length}): common base words from SCOWL / the English
-- Speller Database, in a fixed shuffled order (day N = word N).
-- VALID (${valid.length}): every five-letter word in ENABLE (public domain)
-- plus the answers, sorted (binary search).
--
-- SCOWL / English Speller Database: Copyright 2000-2026 by Kevin Atkinson.
-- Permission to use, copy, modify, distribute, and sell any part of the
-- English Speller Database (ESDB, previously known as SCOWLv2), or word lists
-- created from it, is hereby granted without fee, provided that the above
-- copyright notice appears in all copies and that both the above copyright
-- notice and this notice appear in supporting documentation. Kevin Atkinson
-- makes no representations about the suitability of this database for any
-- purpose. It is provided "as is" without express or implied warranty.
local _, SK = ...
SK.Data = SK.Data or {}

SK.Data.WORDS_ANSWERS =
${chunk(answers.join(""))}

SK.Data.WORDS_VALID =
${chunk(valid.join(""))}
`;
fs.writeFileSync(path.join(__dirname, "..", "Data", "Words.lua"), lua);
console.log("wrote Data/Words.lua:", answers.length, "answers,", valid.length, "valid words");
